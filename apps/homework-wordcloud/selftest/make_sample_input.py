class Sheet:
    """把「A 欄學生編號」一起寫進去（NameMasker 2.0 的輸出樣子）。"""

    def __init__(self, ws):
        self.ws = ws

    def meta(self, row):
        self.ws.append([""] + list(row))

    def header(self, row):
        self.ws.append(["學生編號"] + list(row))

    def data(self, name, row):
        self.ws.append([CODES.get(name, "")] + list(row))

    def plain(self, row=None):
        self.ws.append([""] + list(row or []))


def build(path, folder, qtype, stem, subs):
    """subs = [{'label','type','desc','answers':[...]}]，複刻 Zuvio 匯出版面。"""
    wb = openpyxl.Workbook()
    s = Sheet(wb.active)
    wb.active.title = "sheet1"

    for k, v in [("資料夾名稱", folder), ("問題題型", qtype), ("是否分組", "否"),
                 ("是否匿名", "否"), ("題幹", stem)]:
        s.meta([k, v])
    s.plain()
    s.plain()

    # --- A. 上方彙總表
    s.meta(["問題類型", "", ""] + [f"{x['label']}:{x['type']}" for x in subs])
    s.meta(["問題敘述", "", ""] + [x["desc"] for x in subs])
    s.meta(["正解", "", ""] + ["無正解" for _ in subs])
    s.plain()
    s.header(["學號", "姓名", "作答時間"] + ["回答" for _ in subs])
    for i, n in enumerate(ANSWERED):
        s.data(n, [mask_sid(SIDS[n]), mask_name(n), ts(i)]
               + [deid(x["answers"][i]) for x in subs])
    s.plain()
    s.meta(["未作答學生"])
    s.header(["學號", "姓名"])
    for n in MISSING:
        s.data(n, [mask_sid(SIDS[n]), mask_name(n)])
    s.plain()

    # --- B. 下方逐子題明細區塊
    for x in subs:
        s.meta([f"{x['label']}:{x['type']}"])
        s.meta(["問題敘述", x["desc"]])
        if x["type"] == "單選題":
            s.meta(["正解", "無正解"])
            s.plain()
            s.meta(["選項", "人數", "百分比"])
            for opt in sorted(set(x["answers"])):
                c = x["answers"].count(opt)
                s.meta([opt, c, f"{round(c * 100 / len(x['answers']), 1)}%"])
            s.plain()
            s.header(["學號", "姓名", "正解", "回答"])
            for i, n in enumerate(ANSWERED):
                s.data(n, [mask_sid(SIDS[n]), mask_name(n), "無正解", x["answers"][i]])
        else:
            s.header(["學號", "姓名", "回答"])
            for i, n in enumerate(ANSWERED):
                s.data(n, [mask_sid(SIDS[n]), mask_name(n), deid(x["answers"][i])])
        s.plain()

    # --- 再識別鑰匙工作表（HomeworkWordCloud 必須忽略它）
    link = wb.create_sheet("學生編號連結姓名")
    link.append(["學生編號", "姓名", "學號（原）", "電子郵件（原）", "首次出現列"])
    for i, n in enumerate(NAMES, 1):
        link.append([CODES[n], n, SIDS[n], f"{SIDS[n]}@gms.ndhu.edu.tw", 13 + i])

    os.makedirs(os.path.dirname(path), exist_ok=True)
    wb.save(path)
    print("寫出", path)


