# ---------------------------------------------------------------- xlsx 寫出
def write_block_header(ws, meta):
    for k, v in meta:
        ws.append([k, v])


def build(path, folder, qtype, stem, subs):
    """subs = [{'label','type','desc','answers':[...]}]，複刻 Zuvio 匯出版面。"""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "sheet1"

    write_block_header(ws, [
        ("資料夾名稱", folder),
        ("問題題型", qtype),
        ("是否分組", "否"),
        ("是否匿名", "否"),
        ("題幹", stem),
    ])
    ws.append([])
    ws.append([])

    # --- A. 上方彙總表（問題類型 / 問題敘述 / 正解 對齊在第 4 欄之後）
    ws.append(["問題類型", "", ""] + [f"{s['label']}:{s['type']}" for s in subs])
    ws.append(["問題敘述", "", ""] + [s["desc"] for s in subs])
    ws.append(["正解", "", ""] + ["無正解" for _ in subs])
    ws.append([])
    ws.append(["學號", "姓名", "作答時間"] + ["回答" for _ in subs])
    for i, n in enumerate(ANSWERED):
        ws.append([SIDS[n], n, ts(i)] + [s["answers"][i] for s in subs])
    ws.append([])
    ws.append(["未作答學生"])
    ws.append(["學號", "姓名"])
    for n in MISSING:
        ws.append([SIDS[n], n])
    ws.append([])

    # --- B. 下方逐子題明細區塊
    for s in subs:
        ws.append([f"{s['label']}:{s['type']}"])
        ws.append(["問題敘述", s["desc"]])
        if s["type"] == "單選題":
            ws.append(["正解", "無正解"])
            ws.append([])
            ws.append(["選項", "人數", "百分比"])
            for opt in sorted(set(s["answers"])):
                c = s["answers"].count(opt)
                ws.append([opt, c, f"{round(c * 100 / len(s['answers']), 1)}%"])
            ws.append([])
            ws.append(["學號", "姓名", "正解", "回答"])
            for i, n in enumerate(ANSWERED):
                ws.append([SIDS[n], n, "無正解", s["answers"][i]])
        else:
            ws.append(["學號", "姓名", "回答"])
            for i, n in enumerate(ANSWERED):
                ws.append([SIDS[n], n, s["answers"][i]])
        ws.append([])

    os.makedirs(os.path.dirname(path), exist_ok=True)
    wb.save(path)
    print("寫出", path)


